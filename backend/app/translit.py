"""Транслитерация названий вакансий в URL-slug.

«Машинист буровой установки» → «mashinist-burovoj-ustanovki».

Используется для уникальных адресов детальных карточек:
/vacancy/<slug>. Функция детерминированная — один и тот же slug
всегда получается из одного названия.
"""

_TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def translit_slug(text: str) -> str:
    """Транслитерирует русский текст в slug: только [a-z0-9-].

    Кириллица переводится в латиницу, остальные символы (пробелы,
    пунктуация, кавычки) становятся дефисами, серии дефисов
    схлопываются, по краям дефисы обрезаются.
    """
    parts: list[str] = []
    for ch in (text or "").lower():
        if ch in _TRANSLIT:
            parts.append(_TRANSLIT[ch])
        elif ch.isalnum():
            # Латинские буквы и цифры оставляем как есть.
            parts.append(ch)
        else:
            parts.append("-")

    slug = "".join(parts)
    while "--" in slug:
        slug = slug.replace("--", "-")
    return slug.strip("-")
